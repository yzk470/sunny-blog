    public static boolean isLegacy(String prompt) {
        if (prompt == null || prompt.isBlank()) {
            return true;
        }
        if (prompt.contains(VERSION)) {
            return false;
        }
        return prompt.contains("来自仙舟罗浮的策士")
                || prompt.contains("来自星穹铁道的剑客");
    }
